const { test, expect } = require('@playwright/test');
test('real Backend: HttpOnly session, CSRF, ownership lifecycle and session restoration', async ({ page, context }, testInfo) => {
    const email = `browser-${testInfo.project.name}@example.test`;
    await page.goto('/');
    await expect(page.locator('#accountStatus')).toHaveText('לא מחובר/ת');
    await page.locator('#openAuth').click();
    await page.locator('#switchAuth').click();
    await page.locator('#accountName').fill('Browser Guest');
    await page.locator('#accountEmail').fill(email);
    await page.locator('#accountPassword').fill('browser-test-password-123');
    await page.locator('#authSubmit').click();
    await expect(page.locator('#auth')).not.toBeVisible();
    await expect(page.locator('#accountStatus')).toContainText('Browser Guest');
    const session = (await context.cookies()).find(cookie => cookie.name === 'p360_local_session');
    expect(session.httpOnly).toBe(true);
    expect(session.sameSite).toBe('Lax');
    expect(await page.evaluate(() => document.cookie)).not.toContain('p360_local_session');
    await page.reload();
    await expect(page.locator('#accountStatus')).toContainText('Browser Guest');
    await page.locator('[data-dialog="booking"]').click();
    await page.locator('#fullName').fill('<img src=x onerror=alert(1)>');
    await page.locator('#email').fill(email);
    await page.locator('#hotelSelect').selectOption('TEST');
    await page.locator('#checkIn').fill('2027-06-01');
    await page.locator('#checkOut').fill('2027-06-03');
    const creation = page.waitForResponse(response => response.url().endsWith('/api/reservations') && response.request().method() === 'POST');
    await page.locator('#reservationForm [type=submit]').click();
    const response = await creation;
    expect(response.status()).toBe(201);
    const { reservationId } = await response.json();
    await expect(page.locator('#reservationResult')).toContainText(reservationId);
    await page.locator('#booking .close-dialog').click();
    await page.locator('[data-dialog="lookup"]').click();
    await page.locator('#lookupQuery').fill(reservationId);
    await page.locator('#lookupForm [type=submit]').click();
    await expect(page.locator('#cancelBtn')).toBeVisible();
    await expect(page.locator('#lookupResult img')).toHaveCount(0);
    await expect(page.locator('#lookupResult')).toContainText('<img src=x onerror=alert(1)>');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#cancelBtn').click();
    await expect(page.locator('#lookupResult')).toContainText('בוטלה בהצלחה');
    await page.locator('#lookup .close-dialog').click();
    await page.locator('#logoutButton').click();
    await expect(page.locator('#accountStatus')).toHaveText('לא מחובר/ת');
    expect((await context.request.get('/api/auth/me')).status()).toBe(401);
    await page.locator('#openAuth').click();
    await page.locator('#accountEmail').fill(email);
    await page.locator('#accountPassword').fill('browser-test-password-123');
    await page.locator('#authSubmit').click();
    await expect(page.locator('#auth')).not.toBeVisible();
    await expect(page.locator('#accountStatus')).toContainText('Browser Guest');
    expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0]);
});
